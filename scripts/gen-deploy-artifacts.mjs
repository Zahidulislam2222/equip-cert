#!/usr/bin/env node
/**
 * Generate the shared-VPS deployment artifacts from their single owners (Global Rule 12).
 *
 *   slug / hostname / ports / limits  <- deploy/deploy.config.json
 *   security response headers         <- vercel.json
 *
 * Writing the Caddy site file by hand would fork the security headers away from
 * vercel.json, and the two would drift silently — the VPS would quietly serve the app
 * with no CSP while Vercel kept one. Generating both from the same sources makes that
 * impossible.
 *
 *   node scripts/gen-deploy-artifacts.mjs --release <release-id> [--image-ref <ref>]
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
function arg(name, fallback = null) {
  const i = args.indexOf(`--${name}`);
  if (i !== -1 && args[i + 1]) return args[i + 1];
  if (fallback !== null) return fallback;
  throw new Error(`Missing required argument --${name}`);
}

const release = arg('release');
const deployCfg = JSON.parse(readFileSync('deploy/deploy.config.json', 'utf8'));
const vercelCfg = JSON.parse(readFileSync('vercel.json', 'utf8'));

const { slug, hostname, loopbackPort, containerPort, resources } = deployCfg;
const imageRef = arg('image-ref', `${slug}:${release}`);
const outDir = 'deploy/generated';
mkdirSync(outDir, { recursive: true });

/** Pull the catch-all header block out of vercel.json so both targets stay identical. */
function securityHeaders() {
  const block = vercelCfg.headers?.find((h) => h.source === '/(.*)');
  if (!block) throw new Error('vercel.json has no /(.*) header block to derive from');
  return block.headers;
}

// ---------------------------------------------------------------- Caddy site file
//
// X-Forwarded-For handling is deliberate. Caddy APPENDS to a client-supplied
// X-Forwarded-For, and api/analyze.ts rate-limits on its FIRST value — so a forged
// header would hand any caller a fresh rate-limit bucket. Both branches below
// overwrite the header with a value the client cannot choose.
const headerLines = securityHeaders()
  .map((h) => `        ${h.key} "${h.value.replaceAll('"', '\\"')}"`)
  .join('\n');

const caddySite = `# GENERATED by scripts/gen-deploy-artifacts.mjs — do not hand-edit.
# Source: deploy/deploy.config.json + vercel.json
${hostname} {
    header {
${headerLines}
        -Server
    }

    @cf header CF-Connecting-IP *
    handle @cf {
        reverse_proxy 127.0.0.1:${loopbackPort} {
            header_up X-Forwarded-For {http.request.header.CF-Connecting-IP}
        }
    }

    handle {
        reverse_proxy 127.0.0.1:${loopbackPort} {
            header_up X-Forwarded-For {http.request.remote.host}
        }
    }

    log
}
`;

// ---------------------------------------------------------------- compose file
//
// The port is bound explicitly to 127.0.0.1 so UFW is never bypassed by Docker's
// own iptables rules. The image tag is baked per release so rollback is exact.
const compose = `# GENERATED by scripts/gen-deploy-artifacts.mjs — do not hand-edit.
# Source: deploy/deploy.config.json
name: ${slug}
services:
  web:
    image: ${imageRef}
    restart: unless-stopped
    ports:
      - "127.0.0.1:${loopbackPort}:${containerPort}"
    env_file:
      - ./app.env
    mem_limit: ${resources.memLimit}
    cpus: ${resources.cpus}
    pids_limit: ${resources.pidsLimit}
    read_only: true
    tmpfs:
      - /tmp
    cap_drop:
      - ALL
    security_opt:
      - no-new-privileges:true
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:${containerPort}/healthz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 10s
      timeout: 3s
      retries: 3
      start_period: 5s
`;

writeFileSync(join(outDir, `${slug}.caddy`), caddySite);
writeFileSync(join(outDir, 'compose.yaml'), compose);

console.log(`✓ Generated ${outDir}/${slug}.caddy and ${outDir}/compose.yaml`);
console.log(`  host=${hostname} loopback=${loopbackPort} image=${imageRef}`);
